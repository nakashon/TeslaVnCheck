export function cocRequest(vin: string | null, plate: string | null): string {
  return `שלום,
ברצוני לזהות את תצורת הסוללה של הרכב הבא:
מספר שלדה (VIN): ${vin ?? '[יש להשלים VIN]'}
${plate ? `מספר רישוי: ${plate}\n` : ''}אבקש העתק של תעודת התאמה של היצרן (Certificate of Conformity / CoC), אם קיימת לרכב, כולל סעיף 0.2: Type / Variant / Version ומספר אישור התקינה.
אם לא ניתן לספק CoC, אבקש אישור בכתב של תצורת הסוללה המקורית ושל זהות מארז המתח הגבוה המותקן כיום, כולל יצרן/סוג המארז, מספר חלק מלא וגרסה.
אם המארז הוחלף, אבקש גם את פרטי ההחלפה ואת מספר החלק של המארז שהותקן.
תודה.`
}
